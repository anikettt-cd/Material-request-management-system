@router.post("/{request_id}/reject")
def reject_request(
    request_id: int, 
    payload: schemas.ActionNote, 
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
    current_user: dict = Depends(get_current_user)
):
    safe_username = current_user.get("username", f"User_{current_user.get('user_id')}")

    # 🎯 FIX: Fetch using ORM
    req_to_update = db.query(models.MaterialRequest).filter(models.MaterialRequest.request_id == request_id).first()
    
    if not req_to_update:
        raise HTTPException(status_code=404, detail="Request not found")

    try:
        # 🎯 FIX: Update global tracking state to 'Rejected' via ORM attributes
        req_to_update.status = 'Rejected'
        req_to_update.latest_note = payload.note
        req_to_update.return_to_stage = None

        # 🎯 FIX: Updated Audit Trail via ORM
        new_log = models.WorkflowLog(
            request_id=request_id,
            action_by=current_user.get("user_id"),
            username=safe_username,
            action_type='REJECTED',
            comments=payload.note
        )
        db.add(new_log)
        db.commit()
        
        # Process email alert non-blockingly via background thread
        background_tasks.add_task(
            trigger_workflow_email, 
            db=db, request_id=request_id, target_stage="Terminal", action_type="REJECT", note=payload.note, plant_id=req_to_update.plant_id
        )
        
        return {"message": "Request permanently rejected and notifier triggered."}
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=f"Database Error: {str(e)}")


@router.post("/{request_id}/send-correction")
def send_for_correction(
    request_id: int, 
    payload: schemas.ActionNote, 
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
    current_user: dict = Depends(get_current_user)
):
    safe_username = current_user.get("username", f"User_{current_user.get('user_id')}")

    # 🎯 FIX: Fetch live positional data via ORM
    req_to_update = db.query(models.MaterialRequest).filter(models.MaterialRequest.request_id == request_id).first()
    
    if not req_to_update:
        raise HTTPException(status_code=404, detail="Request not found")

    try:
        # Capture the specific stage that caught the error
        flagging_stage = req_to_update.current_stage
                
        # 🎯 FIX: OVERRIDE ROUTING via ORM attributes
        req_to_update.current_stage = 'Creator'
        req_to_update.status = 'Active'
        req_to_update.return_to_stage = flagging_stage
        req_to_update.latest_note = payload.note
        
        # 🎯 FIX: Updated Audit Trail via ORM
        new_log = models.WorkflowLog(
            request_id=request_id,
            action_by=current_user.get("user_id"),
            username=safe_username,
            action_type='RETURNED',
            comments=f"Returned by {flagging_stage}: {payload.note}" # Embedding the stage into the comment
        )
        db.add(new_log)
        db.commit()
        
        # Trigger email alert directly to the Creator
        background_tasks.add_task(
            trigger_workflow_email, 
            db=db, 
            request_id=request_id, 
            target_stage="Creator", 
            action_type="CORRECTION", 
            note=payload.note, 
            plant_id=req_to_update.plant_id
        )
        
        return {"message": f"Directly routed back to Creator. Once fixed, it will auto-return to {flagging_stage}."}
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=f"Database Error: {str(e)}")